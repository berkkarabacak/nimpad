  nimpad.current_user_id(),
  nimpad.is_member(uuid, text),
  nimpad.member_workspace_ids(text),
  nimpad.co_member_user_ids(),
  nimpad.is_valid_order_key(text),
  nimpad.is_valid_name(text),
  nimpad.uuid_generate_v7()
TO nimpad_app;

