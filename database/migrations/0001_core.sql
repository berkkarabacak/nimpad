-- Application profile; id is the subject of the auth provider (no FK to auth.users, so plain PostgreSQL works).
CREATE TABLE nimpad.users (
  id uuid PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 3 AND 320),
  display_name text CHECK (char_length(display_name) <= 255),
  avatar_url text CHECK (char_length(avatar_url) <= 2048),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE nimpad.workspaces (
  id uuid PRIMARY KEY DEFAULT nimpad.uuid_generate_v7(),
  owner_id uuid NOT NULL REFERENCES nimpad.users (id),
  name text NOT NULL,
  -- Last sequence number handed out to nimpad.sync_events (0002); only nimpad.record_sync_event changes it. Moves
  -- also update the row, without changing it, to take the workspace lock (nimpad.nodes_check_tree).
  event_seq bigint NOT NULL DEFAULT 0 CHECK (event_seq >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT workspaces_name_valid CHECK (nimpad.is_valid_name(name))
);

CREATE TABLE nimpad.workspace_members (
  workspace_id uuid NOT NULL REFERENCES nimpad.workspaces (id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES nimpad.users (id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (workspace_id, user_id)
);

-- Folders and documents. Siblings sort by (position, id) with ordinal comparison, hence COLLATE "C".
CREATE TABLE nimpad.nodes (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES nimpad.workspaces (id) ON DELETE CASCADE,
  parent_id uuid,
  kind text NOT NULL CHECK (kind IN ('folder', 'document')),
  name text NOT NULL,
  position text COLLATE "C" NOT NULL,
  is_pinned boolean NOT NULL DEFAULT false,
  pin_position text COLLATE "C",
  -- Server metadata revision: incremented by nodes_bump_meta_rev whenever name, parent, position, pin or trash
  -- state changes (not on content saves, which move document_contents.content_rev instead).
  meta_rev bigint NOT NULL DEFAULT 1 CHECK (meta_rev >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  content_updated_at timestamptz,
  deleted_at timestamptz,
  trash_batch_id uuid,
  CONSTRAINT nodes_workspace_id_id_key UNIQUE (workspace_id, id),
  -- The parent is in the same workspace. Purging a folder must purge its subtree in the same statement.
  CONSTRAINT nodes_parent_fkey FOREIGN KEY (workspace_id, parent_id) REFERENCES nimpad.nodes (workspace_id, id),
  CONSTRAINT nodes_not_own_parent CHECK (parent_id IS DISTINCT FROM id),
  CONSTRAINT nodes_name_valid CHECK (nimpad.is_valid_name(name)),
  CONSTRAINT nodes_position_valid CHECK (nimpad.is_valid_order_key(position)),
  CONSTRAINT nodes_pin_position_valid CHECK (nimpad.is_valid_order_key(pin_position)),
  CONSTRAINT nodes_pin_position_iff_pinned CHECK (is_pinned = (pin_position IS NOT NULL)),
  CONSTRAINT nodes_folder_has_no_content_time CHECK (kind = 'document' OR content_updated_at IS NULL),
  CONSTRAINT nodes_trash_fields_together CHECK ((deleted_at IS NULL) = (trash_batch_id IS NULL))
);

-- The current text of a document. workspace_id is denormalized for row-level security and is kept equal to the
-- node's workspace by the composite foreign key.
CREATE TABLE nimpad.document_contents (
  node_id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL,
  text text NOT NULL,
  format text NOT NULL DEFAULT 'plain' CHECK (format IN (
    'plain', 'markdown', 'json', 'xml', 'yaml', 'python', 'groovy', 'javascript', 'typescript', 'csharp', 'sql',
    'powershell', 'ini', 'css', 'html'
  )),
  -- Server content revision: incremented by document_contents_bump_content_rev whenever text or format changes.
  content_rev bigint NOT NULL DEFAULT 1 CHECK (content_rev >= 1),
  checksum text NOT NULL,
  char_count integer NOT NULL CHECK (char_count >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'agent', 'system', 'import')),
  updated_by_id uuid,
  CONSTRAINT document_contents_node_fkey FOREIGN KEY (workspace_id, node_id)
    REFERENCES nimpad.nodes (workspace_id, id) ON DELETE CASCADE,
  -- Managed notes are stored canonical (LF line endings only), so the hash of the stored text below is exactly
  -- the shared content checksum ('sha256:' + lowercase hex SHA-256 of the canonical text's UTF-8 bytes).
  CONSTRAINT document_contents_text_canonical CHECK (strpos(text, E'\r') = 0),
  CONSTRAINT document_contents_checksum_matches CHECK (
    checksum LIKE 'sha256:%'
    AND checksum = 'sha256:' || encode(sha256(convert_to(text, 'UTF8')), 'hex')
  )
);

-- Immutable snapshots: UPDATE is blocked by trigger. Rows go away only with their node (purge) or retention.
-- A revision snapshots the document's current content: `revision` is the content_rev it captures, and text, format
-- and checksum are those of document_contents at that moment (document_revisions_match_content). So the API writes
-- the content first and then the revision, in the same transaction. Not every content_rev needs a revision.
CREATE TABLE nimpad.document_revisions (
  id uuid PRIMARY KEY DEFAULT nimpad.uuid_generate_v7(),
  node_id uuid NOT NULL,
  workspace_id uuid NOT NULL,
  revision bigint NOT NULL CHECK (revision >= 1),
  text text NOT NULL,
  format text NOT NULL CHECK (format IN (
    'plain', 'markdown', 'json', 'xml', 'yaml', 'python', 'groovy', 'javascript', 'typescript', 'csharp', 'sql',
    'powershell', 'ini', 'css', 'html'
  )),
  checksum text NOT NULL,
  actor_kind text NOT NULL CHECK (actor_kind IN ('user', 'agent', 'system', 'import')),
  actor_id uuid,
  change_summary text CHECK (char_length(change_summary) <= 2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT document_revisions_node_fkey FOREIGN KEY (workspace_id, node_id)
    REFERENCES nimpad.nodes (workspace_id, id) ON DELETE CASCADE,
  CONSTRAINT document_revisions_text_canonical CHECK (strpos(text, E'\r') = 0),
  CONSTRAINT document_revisions_checksum_matches CHECK (
    checksum LIKE 'sha256:%'
    AND checksum = 'sha256:' || encode(sha256(convert_to(text, 'UTF8')), 'hex')
  )
);
-- Unique per document, and the index that serves "latest revisions first".
CREATE UNIQUE INDEX document_revisions_node_revision_key ON nimpad.document_revisions (node_id, revision DESC);

