-- True when the current user has at least min_role ('viewer' < 'editor' < 'owner') in the workspace.
CREATE FUNCTION nimpad.is_member(workspace uuid, min_role text) RETURNS boolean
  LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path = ''
  AS $$
DECLARE
  allowed text[] := nimpad.roles_at_least(min_role);
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM nimpad.workspace_members m
    WHERE m.workspace_id = is_member.workspace
      AND m.user_id = nimpad.current_user_id()
      AND m.role = ANY (allowed)
  );
END
$$;

-- The workspaces in which the current user has at least min_role. Policies use it as
-- `workspace_id IN (SELECT nimpad.member_workspace_ids('viewer'))`, which runs once per statement (a hashed
-- subplan) instead of once per row.
CREATE FUNCTION nimpad.member_workspace_ids(min_role text) RETURNS SETOF uuid
  LANGUAGE plpgsql STABLE SECURITY DEFINER ROWS 10
  SET search_path = ''
  AS $$
DECLARE
  allowed text[] := nimpad.roles_at_least(min_role);
BEGIN
  RETURN QUERY
    SELECT m.workspace_id
    FROM nimpad.workspace_members m
    WHERE m.user_id = nimpad.current_user_id()
      AND m.role = ANY (allowed);
END
$$;

-- The users who share at least one workspace with the current user (including the current user once they are in
-- any workspace). The users policy uses it so members can see each other's profiles: member lists, and the
-- authors of revisions and events.
CREATE FUNCTION nimpad.co_member_user_ids() RETURNS SETOF uuid
  LANGUAGE sql STABLE SECURITY DEFINER ROWS 20
  SET search_path = ''
  AS $$
    SELECT DISTINCT other.user_id
    FROM nimpad.workspace_members mine
    JOIN nimpad.workspace_members other ON other.workspace_id = mine.workspace_id
    WHERE mine.user_id = nimpad.current_user_id()
  $$;

