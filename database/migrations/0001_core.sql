-- Creating a workspace makes its owner an 'owner' member, so the API never has to bootstrap membership.
CREATE FUNCTION nimpad.workspaces_add_owner_member() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = ''
  AS $$
BEGIN
  INSERT INTO nimpad.workspace_members (workspace_id, user_id, role) VALUES (NEW.id, NEW.owner_id, 'owner');
  RETURN NULL;
END
$$;

-- The workspace's owner_id always keeps an 'owner' membership (a workspace cannot be orphaned). Rows deleted
-- by the cascade from a deleted workspace pass, because the workspace row is already gone.
CREATE FUNCTION nimpad.workspace_members_protect_owner() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = ''
  AS $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM nimpad.workspaces w WHERE w.id = OLD.workspace_id AND w.owner_id = OLD.user_id
  ) AND (
    TG_OP = 'DELETE'
    OR NEW.role <> 'owner'
    OR NEW.user_id IS DISTINCT FROM OLD.user_id
    OR NEW.workspace_id IS DISTINCT FROM OLD.workspace_id
  ) THEN
    RAISE EXCEPTION 'the owner of workspace % must remain an owner member', OLD.workspace_id
      USING ERRCODE = 'check_violation', CONSTRAINT = 'workspace_members_owner_kept',
            SCHEMA = 'nimpad', TABLE = 'workspace_members';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END
$$;

-- Tree rules for nodes: kind and workspace never change, a parent is a folder of the same workspace, and the
-- tree stays acyclic.
--
-- Only a parent change can close a cycle: a new node has no descendants yet (a child's parent must already
-- exist), so inserts need no lock, and creating nodes in different folders never waits on another transaction.
--
-- A parent change first updates the workspace row (to the same values). That is the row lock that
-- nimpad.record_sync_event takes as well, so moves and sync events in a workspace queue behind one lock, held
-- until commit, in whatever order a transaction does them. Then the ancestors of the new parent are walked:
--   * READ COMMITTED (the API's level): the walk is a new statement with a fresh snapshot, which includes every
--     move committed by the previous lock holder. Of two opposite moves (A under B, B under A), the second sees
--     the first and is rejected.
--   * REPEATABLE READ and SERIALIZABLE: the snapshot can predate a move that committed meanwhile, so the walk
--     could miss it. But that move also updated the workspace row, and updating a row that changed after the
--     snapshot fails with a serialization failure (40001), which the caller retries. (A lock-only SELECT ... FOR
--     UPDATE would not do: only a new row version makes the stale snapshot fail.)
-- A transaction that locks other rows before moving (renaming one node, then moving another) can still deadlock
-- with a transaction holding those rows; PostgreSQL aborts one of them with 40P01, retried like 40001.
CREATE FUNCTION nimpad.nodes_check_tree() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = ''
  AS $$
DECLARE
  parent_kind text;
  creates_cycle boolean;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.kind IS DISTINCT FROM OLD.kind THEN
      RAISE EXCEPTION 'the kind of node % cannot change', OLD.id
        USING ERRCODE = 'check_violation', CONSTRAINT = 'nodes_kind_immutable', SCHEMA = 'nimpad', TABLE = 'nodes';
    END IF;
    IF NEW.workspace_id IS DISTINCT FROM OLD.workspace_id OR NEW.id IS DISTINCT FROM OLD.id THEN
      RAISE EXCEPTION 'the id and workspace of node % cannot change', OLD.id
        USING ERRCODE = 'check_violation', CONSTRAINT = 'nodes_identity_immutable', SCHEMA = 'nimpad',
              TABLE = 'nodes';
    END IF;
    IF NEW.parent_id IS NOT DISTINCT FROM OLD.parent_id THEN
      RETURN NEW;
    END IF;
  END IF;

  IF NEW.parent_id IS NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.parent_id = NEW.id THEN
    RAISE EXCEPTION 'node % cannot be its own parent', NEW.id
      USING ERRCODE = 'check_violation', CONSTRAINT = 'nodes_no_cycle', SCHEMA = 'nimpad', TABLE = 'nodes';
  END IF;

  SELECT n.kind INTO parent_kind
  FROM nimpad.nodes n
  WHERE n.workspace_id = NEW.workspace_id AND n.id = NEW.parent_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'parent % is not a node of workspace %', NEW.parent_id, NEW.workspace_id
      USING ERRCODE = 'foreign_key_violation', CONSTRAINT = 'nodes_parent_fkey', SCHEMA = 'nimpad', TABLE = 'nodes';
  END IF;
  IF parent_kind <> 'folder' THEN
    RAISE EXCEPTION 'parent % is a %, only folders can contain nodes', NEW.parent_id, parent_kind
      USING ERRCODE = 'check_violation', CONSTRAINT = 'nodes_parent_is_folder', SCHEMA = 'nimpad', TABLE = 'nodes';
  END IF;

  IF TG_OP = 'INSERT' THEN
    RETURN NEW;
  END IF;

  UPDATE nimpad.workspaces w SET event_seq = w.event_seq WHERE w.id = NEW.workspace_id;

  -- UNION (not UNION ALL) terminates even if the data somehow already contains a cycle. "parent_id = NEW.id"
  -- also catches rows moved earlier in the same statement (one UPDATE that swaps two parents).
  WITH RECURSIVE ancestors (id, parent_id) AS (
    SELECT n.id, n.parent_id FROM nimpad.nodes n WHERE n.id = NEW.parent_id
    UNION
    SELECT n.id, n.parent_id FROM nimpad.nodes n JOIN ancestors a ON n.id = a.parent_id
  )
  SELECT EXISTS (SELECT 1 FROM ancestors a WHERE a.id = NEW.id OR a.parent_id = NEW.id) INTO creates_cycle;

  IF creates_cycle THEN
    RAISE EXCEPTION 'moving node % under % would create a cycle', NEW.id, NEW.parent_id
      USING ERRCODE = 'check_violation', CONSTRAINT = 'nodes_no_cycle', SCHEMA = 'nimpad', TABLE = 'nodes';
  END IF;
  RETURN NEW;
END
$$;

-- document_contents and document_revisions rows belong to documents, not folders.
CREATE FUNCTION nimpad.require_document_node() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = ''
  AS $$
DECLARE
  node_kind text;
BEGIN
  SELECT n.kind INTO node_kind
  FROM nimpad.nodes n
  WHERE n.workspace_id = NEW.workspace_id AND n.id = NEW.node_id;
  -- A missing node is reported by the foreign key.
  IF FOUND AND node_kind <> 'document' THEN
    RAISE EXCEPTION 'node % is a %, only documents have content', NEW.node_id, node_kind
      USING ERRCODE = 'check_violation', CONSTRAINT = TG_TABLE_NAME || '_node_is_document', SCHEMA = 'nimpad',
            TABLE = TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END
$$;

-- Server revisions only move forward, and only the database moves them (nimpad_app cannot write the columns, and a
-- value set by any other role is overwritten). Optimistic concurrency then needs nothing from the caller but
-- `WHERE meta_rev = <expected>` / `WHERE content_rev = <expected>`, with the new value from RETURNING.
CREATE FUNCTION nimpad.nodes_bump_meta_rev() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
  AS $$
BEGIN
  IF (NEW.parent_id, NEW.name, NEW.position, NEW.is_pinned, NEW.pin_position, NEW.deleted_at, NEW.trash_batch_id)
     IS DISTINCT FROM
     (OLD.parent_id, OLD.name, OLD.position, OLD.is_pinned, OLD.pin_position, OLD.deleted_at, OLD.trash_batch_id)
  THEN
    NEW.meta_rev := OLD.meta_rev + 1;
  ELSE
    NEW.meta_rev := OLD.meta_rev;
  END IF;
  RETURN NEW;
END
$$;

-- Text and format are the content. The checksum stands in for the text: the CHECK constraints tie the two together
-- for every row that can be stored, and comparing it avoids comparing two possibly large texts.
CREATE FUNCTION nimpad.document_contents_bump_content_rev() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
  AS $$
BEGIN
  IF (NEW.checksum, NEW.format) IS DISTINCT FROM (OLD.checksum, OLD.format) THEN
    NEW.content_rev := OLD.content_rev + 1;
  ELSE
    NEW.content_rev := OLD.content_rev;
  END IF;
  RETURN NEW;
END
$$;

-- A new revision must be a snapshot of the document's current content (see the document_revisions table). Runs
-- as an AFTER trigger, so row-level security has already accepted the row: the caller is an editor of the
-- workspace (or a role that bypasses RLS), and the error below reveals nothing they could not read anyway.
CREATE FUNCTION nimpad.document_revisions_match_content() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = ''
  AS $$
DECLARE
  content nimpad.document_contents%ROWTYPE;
BEGIN
  SELECT * INTO content
  FROM nimpad.document_contents c
  WHERE c.workspace_id = NEW.workspace_id AND c.node_id = NEW.node_id;
  IF NOT FOUND
     OR (NEW.revision, NEW.checksum, NEW.format) IS DISTINCT FROM (content.content_rev, content.checksum, content.format)
  THEN
    RAISE EXCEPTION 'revision % of document % does not match its current content (content_rev %)',
        NEW.revision, NEW.node_id, coalesce(content.content_rev::text, 'none')
      USING ERRCODE = 'check_violation', CONSTRAINT = 'document_revisions_match_content', SCHEMA = 'nimpad',
            TABLE = 'document_revisions',
            HINT = 'Write the content first, then insert the revision with revision = content_rev.';
  END IF;
  RETURN NULL;
END
$$;

