-- 0001_core: the core document model (users, workspaces, membership, the node tree, document contents and
-- revisions, links, activity and the audit log), with row-level security for the API's nimpad_app role.
--
-- Conventions (docs/architecture.md, "Server data model"):
--   * Everything lives in schema nimpad. Every table has ENABLE + FORCE ROW LEVEL SECURITY.
--   * Policies identify the caller with nimpad.current_user_id(), which reads the transaction-local setting
--     app.user_id (set by the API with set_config('app.user_id', $1, true)). auth.uid() is deliberately not
--     used, so the same SQL runs on plain PostgreSQL and on Supabase.
--   * The API connects as nimpad_app (or a LOGIN role that is a member of it): not the owner, no BYPASSRLS.
--   * Membership lookups and integrity triggers are SECURITY DEFINER functions owned by the migration role.
--     They must read rows the caller cannot see (and policies on workspace_members would otherwise recurse),
--     so the migration role has to bypass RLS: a superuser, or a role with BYPASSRLS such as Supabase's
--     postgres role. The first block below enforces that.
--   * IDs are UUIDv7 generated by clients or the API; ordering keys use COLLATE "C" (ordinal comparison).
--   * Constraints mirror the shared contracts (packages/contracts) so that no write path, including one that skips
--     the API's validation, can store a value that clients reject: canonical LF-only text with a matching
--     checksum, fractional-index position keys, node names measured in UTF-16 code units.
--   * Server revisions (nodes.meta_rev, document_contents.content_rev) are maintained by triggers and only move
--     forward; the API reads them and compares them, it never sets them.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = current_user AND (rolsuper OR rolbypassrls)
  ) THEN
    RAISE EXCEPTION 'nimpad migrations must run as a superuser or a role with BYPASSRLS (current role: %)', current_user
      USING HINT = 'The SECURITY DEFINER helpers in schema nimpad read tables that use FORCE ROW LEVEL SECURITY.';
  END IF;
  -- Text is Unicode end to end, and the name rules below count UTF-16 code units with \U escapes.
  IF pg_catalog.current_setting('server_encoding') <> 'UTF8' THEN
    RAISE EXCEPTION 'nimpad requires a UTF8 database (this one is %)', pg_catalog.current_setting('server_encoding');
  END IF;
END
$$;

CREATE SCHEMA nimpad;
REVOKE ALL ON SCHEMA nimpad FROM PUBLIC;

-- The API role. Roles are cluster-wide, so another database may already have created it (possibly at the same
-- moment, hence the exception handler). Development may later give it LOGIN (see database/src/cli.ts).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'nimpad_app') THEN
    BEGIN
      CREATE ROLE nimpad_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
    EXCEPTION WHEN duplicate_object OR unique_violation THEN
      NULL;
    END;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'nimpad_app' AND (rolsuper OR rolbypassrls)) THEN
    RAISE EXCEPTION 'role nimpad_app must not be a superuser or have BYPASSRLS: row-level security would not apply';
  END IF;
END
$$;

GRANT USAGE ON SCHEMA nimpad TO nimpad_app;

