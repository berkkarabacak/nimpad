-- The authenticated user of the current transaction, or NULL when app.user_id is unset or empty (a custom
-- setting reverts to '' rather than NULL once a transaction that set it locally ends).
CREATE FUNCTION nimpad.current_user_id() RETURNS uuid
  LANGUAGE sql STABLE PARALLEL SAFE SECURITY INVOKER
  SET search_path = ''
  AS $$ SELECT NULLIF(pg_catalog.current_setting('app.user_id', true), '')::uuid $$;

-- The workspace roles that satisfy min_role. Ranking: owner > editor > viewer.
CREATE FUNCTION nimpad.roles_at_least(min_role text) RETURNS text[]
  LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE
  SET search_path = ''
  AS $$
BEGIN
  CASE min_role
    WHEN 'viewer' THEN RETURN ARRAY['viewer', 'editor', 'owner'];
    WHEN 'editor' THEN RETURN ARRAY['editor', 'owner'];
    WHEN 'owner' THEN RETURN ARRAY['owner'];
    ELSE RAISE EXCEPTION 'unknown workspace role "%"', min_role USING ERRCODE = 'invalid_parameter_value';
  END CASE;
END
$$;

-- RFC 9562 UUID version 7: 48-bit Unix milliseconds, then random bits. The default for rows the server creates
-- (PostgreSQL 16 has no built-in v7); clients still supply their own ids for nodes.
CREATE FUNCTION nimpad.uuid_generate_v7() RETURNS uuid
  LANGUAGE sql VOLATILE PARALLEL SAFE
  SET search_path = ''
  AS $$
    -- Overwrite the first 6 bytes of a random v4 UUID with the timestamp, then turn version 4 (0100) into
    -- version 7 (0111) by setting bits 52 and 53; the variant bits are already correct.
    SELECT encode(
      set_bit(
        set_bit(
          overlay(
            uuid_send(gen_random_uuid())
            PLACING substring(int8send(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint) FROM 3)
            FROM 1 FOR 6),
          52, 1),
        53, 1),
      'hex')::uuid
  $$;

CREATE FUNCTION nimpad.set_updated_at() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
  AS $$
BEGIN
  NEW.updated_at := pg_catalog.now();
  RETURN NEW;
END
$$;

-- True when key is a fractional-index position key, exactly as isValidOrderKey in packages/contracts decides:
-- only base-62 digits; the head character fixes the length of the integer part ('a'..'z' mean 2..27 characters,
-- 'A'..'Z' mean 27..2); a fractional part, if any, does not end with '0'; and the smallest integer ('A' followed by
-- 26 zeros) is not a key. A stored invalid key would make every client fail to generate a key next to it.
CREATE FUNCTION nimpad.is_valid_order_key(key text) RETURNS boolean
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
  SET search_path = ''
  AS $$
    SELECT key ~ '^[0-9A-Za-z]+$'
      AND key <> 'A00000000000000000000000000'
      AND coalesce(
        pg_catalog.char_length(key) = integer_length
          OR (pg_catalog.char_length(key) > integer_length AND pg_catalog.right(key, 1) <> '0'),
        false)
    FROM (
      -- Code points, not collation order: 'a' (97) .. 'z' (122) give 2..27, 'Z' (90) .. 'A' (65) give 2..27.
      SELECT CASE
        WHEN pg_catalog.ascii(key) BETWEEN 97 AND 122 THEN pg_catalog.ascii(key) - 95
        WHEN pg_catalog.ascii(key) BETWEEN 65 AND 90 THEN 92 - pg_catalog.ascii(key)
      END AS integer_length
    ) AS head
  $$;

-- True when name is a valid node or workspace name, exactly as NodeName in packages/contracts decides
-- (fixtures/node-names.json): 1 to 255 UTF-16 code units (the unit of .NET and JavaScript string lengths, so a
-- character outside the Basic Multilingual Plane counts twice); no C0 control character or DEL; and neither
-- starting nor ending with white space, which also rules out a blank name. White space is Unicode White_Space,
-- the set of .NET's char.IsWhiteSpace: it includes U+0085 and U+00A0 but not U+FEFF or U+200B.
CREATE FUNCTION nimpad.is_valid_name(name text) RETURNS boolean
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
  SET search_path = ''
  AS $$
    SELECT pg_catalog.char_length(name)
             + pg_catalog.char_length(pg_catalog.regexp_replace(name, '[^\U00010000-\U0010FFFF]', '', 'g'))
           BETWEEN 1 AND 255
      AND name !~ '[\x01-\x1f\x7f]'
      AND name !~ '^[\t\n\v\f\r \u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]'
      AND name !~ '[\t\n\v\f\r \u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000]$'
  $$;

-- Blocks UPDATE/DELETE/TRUNCATE on append-only tables, for every role including the owner.
CREATE FUNCTION nimpad.reject_change() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
  AS $$
BEGIN
  RAISE EXCEPTION '%.% is append-only: % is not allowed', TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP
    USING ERRCODE = 'insufficient_privilege', SCHEMA = TG_TABLE_SCHEMA, TABLE = TG_TABLE_NAME;
END
$$;

